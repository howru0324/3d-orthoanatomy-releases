const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const zlib = require('node:zlib');
const version = '0.4.2-beta.3';
const exe = '3D-orthoanatomy-Test-Setup-' + version + '.exe';
const root = process.argv[2];
const names = [exe, exe + '.blockmap', 'beta.yml'];
const walk = dir => fs.readdirSync(dir, {withFileTypes:true}).flatMap(e => e.isDirectory() ? walk(path.join(dir,e.name)) : [path.join(dir,e.name)]);
const all = walk(root);
if(all.length !== 3 || names.some(n => !all.some(p=>path.basename(p)===n))) throw Error('Bundle must contain only the three release assets');
const selected = Object.fromEntries(names.map(n => [n, all.find(p=>path.basename(p)===n)]));
const manifest = fs.readFileSync(selected['beta.yml'],'utf8');
if (!manifest.includes('version: '+version) || !manifest.includes(exe)) throw Error('Manifest version/path mismatch');
const data=fs.readFileSync(selected[exe]);
if(data[0]!==77 || data[1]!==90) throw Error('Not a Windows executable');
const expected = manifest.match(/^sha512: (.+)$/m)?.[1].trim();
if(expected !== crypto.createHash('sha512').update(data).digest('base64')) throw Error('Manifest checksum mismatch');
if(!manifest.includes('size: '+data.length)) throw Error('Manifest size mismatch');
const map=JSON.parse(zlib.gunzipSync(fs.readFileSync(selected[exe+'.blockmap'])));
if(map.version!=='2'||!map.files?.length) throw Error('Invalid blockmap');
const assets=names.map(name=>({name,file:selected[name],size:fs.statSync(selected[name]).size,digest:'sha256:'+crypto.createHash('sha256').update(fs.readFileSync(selected[name])).digest('hex')}));
fs.writeFileSync(path.join(process.env.RUNNER_TEMP,'verified-assets.json'),JSON.stringify(assets));
console.log(JSON.stringify({version,manifestVerified:true,blockmapVerified:true,assets:assets.map(({file,...a})=>a)}));
